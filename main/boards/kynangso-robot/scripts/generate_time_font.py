"""Rebuild board-local Noto Sans Vietnamese fonts (not part of firmware builds)."""

import argparse
import hashlib
import os
from pathlib import Path
import unicodedata
import shutil
import subprocess
import tempfile
import urllib.request

BOARD = Path(__file__).resolve().parents[1]
SOURCE = "https://raw.githubusercontent.com/notofonts/noto-fonts/main/hinted/ttf/NotoSans/NotoSans-Regular.ttf"
SHA256 = "b85c38ecea8a7cfb39c24e395a4007474fa5a4fc864f6ee33309eb4948d232d5"
BOLD_SOURCE = "https://raw.githubusercontent.com/notofonts/noto-fonts/main/hinted/ttf/NotoSans/NotoSans-Bold.ttf"
BOLD_SHA256 = "c976e4b1b99edc88775377fcc21692ca4bfa46b6d6ca6522bfda505b28ff9d6a"
RANGES = (
    "0x20-0x7e,0xa0-0xff,0x102-0x103,0x110-0x111,0x128-0x129,0x168-0x169,"
    "0x1a0-0x1a1,0x1af-0x1b0,"
    "0x1ea0-0x1ef9,0x300-0x303,0x306,0x309,0x31b,0x323,"
    "0x2013-0x2014,0x2018-0x2019,0x201c-0x201d,0x2022,0x2026"
)


def validate_vietnamese_glyph_coverage():
    """Fail early if the generated fonts would omit any Vietnamese vowel or tone."""
    covered = set()
    for item in RANGES.split(","):
        start, separator, end = item.partition("-")
        first = int(start, 16)
        last = int(end, 16) if separator else first
        covered.update(range(first, last + 1))

    tones = ("", "\u0300", "\u0301", "\u0309", "\u0303", "\u0323")
    missing = set()
    for base in "aăâeêioôơuưy":
        for letter in (base, base.upper()):
            for tone in tones:
                composed = unicodedata.normalize("NFC", letter + tone)
                decomposed = unicodedata.normalize("NFD", composed)
                for form in (composed, decomposed):
                    missing.update(
                        ord(char) for char in form if ord(char) > 127 and ord(char) not in covered
                    )

    missing.update(ord(char) for char in "đĐ" if ord(char) not in covered)
    if missing:
        names = ", ".join(
            f"U+{codepoint:04X} {unicodedata.name(chr(codepoint), 'UNKNOWN')}"
            for codepoint in sorted(missing)
        )
        raise SystemExit(f"Vietnamese glyph ranges are incomplete: {names}")


def main():
    validate_vietnamese_glyph_coverage()
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", type=Path, help="Existing source TTF; otherwise download it")
    parser.add_argument("--weight", choices=("regular", "bold"), default="regular")
    parser.add_argument("--size", type=int, choices=(10, 14, 16, 20, 36), default=14,
                        help="Font size in pixels (default: 14)")
    args = parser.parse_args()
    if (args.weight, args.size) not in {
        ("regular", 10), ("regular", 14), ("regular", 16), ("bold", 20), ("bold", 36)
    }:
        parser.error("regular fonts support 10/14/16 px; bold fonts support 20/36 px")
    with tempfile.TemporaryDirectory(prefix="kynangso-time-font-") as temporary:
        font = args.font
        if font is None:
            is_bold = args.weight == "bold"
            font = Path(temporary) / ("NotoSans-Bold.ttf" if is_bold else "NotoSans-Regular.ttf")
            urllib.request.urlretrieve(BOLD_SOURCE if is_bold else SOURCE, font)
        expected_hash = BOLD_SHA256 if args.weight == "bold" else SHA256
        if hashlib.sha256(font.read_bytes()).hexdigest() != expected_hash:
            raise SystemExit("Source font SHA-256 mismatch; refusing to change firmware assets")
        npx = shutil.which("npx.cmd" if os.name == "nt" else "npx")
        if not npx:
            raise SystemExit("Node.js/npx is required only when regenerating this font")
        outputs = {
            ("regular", 10): ("robot_oled_font_10", "display/oled/robot_oled_font_10.c"),
            ("regular", 14): ("robot_time_font_14", "display/tft/robot_time_font.c"),
            ("regular", 16): ("robot_info_font_16", "display/tft/robot_info_font.c"),
            ("bold", 20): ("robot_info_bold_20", "display/tft/robot_info_bold_20.c"),
            ("bold", 36): ("robot_info_bold_36", "display/tft/robot_info_bold_36.c"),
        }
        font_name, output_path = outputs[(args.weight, args.size)]
        output = BOARD / output_path
        glyph_ranges = RANGES
        subprocess.run([
            npx, "--yes", "lv_font_conv@1.5.3", "--size", str(args.size), "--bpp", "1",
            "--no-compress", "--no-kerning", "--font", str(font.resolve()),
            "-r", glyph_ranges, "--format", "lvgl", "--lv-include", "lvgl.h",
            "--lv-font-name", font_name, "-o", str(output),
        ], check=True)
        # Avoid embedding the generator machine's filesystem paths in source.
        content = output.read_text(encoding="utf-8")
        lines = content.splitlines()
        while lines and not lines[-1]:
            lines.pop()
        content = "\n".join(
            " * Generated by scripts/generate_time_font.py; Noto Sans SIL OFL-1.1."
            if " * Opts:" in line else line
            for line in lines
        ) + "\n"
        output.write_text(content, encoding="utf-8")
        print(f"Generated {output} ({output.stat().st_size} source bytes)")


if __name__ == "__main__":
    main()
