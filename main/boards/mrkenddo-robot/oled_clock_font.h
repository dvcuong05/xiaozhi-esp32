inline const uint8_t* GetGlyph(char character) {
    if (character >= '0' && character <= '9') {
        return kDigits[character - '0'];
    }
    if (character == ':') {
        return kColon;
    }
    if (character == '-') {
        return kDash;
    }
    if (character == ' ') {
        return kSpace;
    }
    if (character == '.') {
        return kPeriod;
    }
    if (character == ',') {
        return kComma;
    }
    if (character == '/') {
        return kSlash;
    }
    if (character == '_') {
        return kUnderscore;
    }
    if (character == '!') {
        return kExclamation;
    }
    if (character == '?') {
        return kQuestionMark;
    }
    if (character >= 'A' && character <= 'Z') {
        return kLetters[character - 'A'];
    }
    return kQuestion;
}

