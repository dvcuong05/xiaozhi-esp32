"""Rebuild the board-local Noto Sans 14 px Vietnamese font (not part of firmware builds)."""

import argparse
import hashlib
import os
from pathlib import Path
import shutil
import subprocess
import tempfile
import urllib.request

BOARD = Path(__file__).resolve().parents[1]
SOURCE = "https://raw.githubusercontent.com/notofonts/noto-fonts/main/hinted/ttf/NotoSans/NotoSans-Regular.ttf"
SHA256 = "b85c38ecea8a7cfb39c24e395a4007474fa5a4fc864f6ee33309eb4948d232d5"
RANGES = (
    "0x20-0x7e,0xa0-0xff,0x102-0x103,0x110-0x111,0x1a0-0x1a1,0x1af-0x1b0,"
    "0x1ea0-0x1ef9,0x300-0x303,0x306,0x309,0x31b,0x323,"
    "0x2013-0x2014,0x2018-0x2019,0x201c-0x201d,0x2022,0x2026"
)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", type=Path, help="Existing source TTF; otherwise download it")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix="mrkenddo-time-font-") as temporary:
        font = args.font
        if font is None:
            font = Path(temporary) / "NotoSans-Regular.ttf"
            urllib.request.urlretrieve(SOURCE, font)
        if hashlib.sha256(font.read_bytes()).hexdigest() != SHA256:
            raise SystemExit("Source font SHA-256 mismatch; refusing to change firmware assets")
        npx = shutil.which("npx.cmd" if os.name == "nt" else "npx")
        if not npx:
            raise SystemExit("Node.js/npx is required only when regenerating this font")
        output = BOARD / "robot_time_font.c"
        subprocess.run([
            npx, "--yes", "lv_font_conv@1.5.3", "--size", "14", "--bpp", "1",
            "--no-compress", "--no-kerning", "--font", str(font.resolve()),
            "-r", RANGES, "--format", "lvgl", "--lv-include", "lvgl.h",
            "--lv-font-name", "robot_time_font_14", "-o", str(output),
        ], check=True)
        # Avoid embedding the generator machine's filesystem paths in source.
        content = output.read_text(encoding="utf-8")
        content = "\n".join(
            " * Generated by scripts/generate_time_font.py; Noto Sans SIL OFL-1.1."
            if " * Opts:" in line else line
            for line in content.splitlines()
        ) + "\n"
        output.write_text(content, encoding="utf-8")
        print(f"Generated {output} ({output.stat().st_size} source bytes)")


if __name__ == "__main__":
    main()
